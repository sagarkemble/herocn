function tokenLines(tokens: Record<string, string>, indent: string, withCharts: boolean): string[] {
  const out: string[] = [];

  for (const item of ORDER) {
    if (Array.isArray(item)) out.push(`${indent}${item[0]}: ${item[1]};`);
    else if (item === "#charts") {
      if (withCharts) out.push(...CHARTS.map((l) => indent + l));
    } else if (item === "") out.push("");
    else if (item.startsWith("/*")) out.push(indent + item);
    else if (tokens[item] !== undefined) out.push(`${indent}${item}: ${tokens[item]};`);
  }

  return out;
}

/** Field selectors that use `rounded-xl` in the skill (the closest thing to HeroUI's --field-radius). */
export const FIELD_SELECTORS = [
  '[data-slot="input"]',
  '[data-slot="textarea"]',
  '[data-slot="select-trigger"]',
  '[data-slot="native-select"]',
  '[data-slot="input-group"]',
  '[data-slot="input-otp-slot"]',
];

/** Default skill field radius: `rounded-xl` = calc(var(--radius) * 1.5). */
function fieldRadiusIsDefault(theme: SkillTheme) {
  const r = parseFloat(theme.radius) || 0;
  const f = parseFloat(theme.fieldRadius) || 0;

  return Math.abs(r * 1.5 - f) < 1e-9;
}

export function generateGlobalsCss(variables: ThemeVariables): string {
  const theme = computeSkillTheme(variables);
  const {fontMeta} = theme;
  const lines: string[] = [];

  lines.push(
    "/* Generated by the /themes editor (HeroUI theme-builder algorithm, mapped to shadcn-to-heroui tokens).",
    "   Paste over the :root, .dark and font lines of app/globals.css. */",
    "",
  );
  if (fontMeta.cdnUrl) lines.push(`@import url("${fontMeta.cdnUrl}");`, "");
  lines.push(":root {", ...PRIMITIVES, `\t--radius: ${theme.radius};`);
  lines.push(...tokenLines(theme.light, "\t", true));
  lines.push("}", "");
  lines.push(".dark {", ...tokenLines(theme.dark, "\t", true), "}", "");
  lines.push("@theme inline {", `\t--font-sans: "${fontMeta.family}", sans-serif;`, "}");

  if (!fieldRadiusIsDefault(theme)) {
    lines.push(
      "",
      "/* Radius Form. The skill has no --field-radius token: its fields use rounded-xl (= --radius x 1.5).",
      "   These rules give fields their own radius. */",
      ":root {",
      `\t--field-radius: ${theme.fieldRadius};`,
      "}",
      `${FIELD_SELECTORS.join(",\n")} {`,
      "\tborder-radius: var(--field-radius);",
      "}",
    );
  }

  return `${lines.join("\n")}\n`;
}

function block(selector: string, decls: Record<string, string>): string {
  const body = Object.entries(decls)
    .map(([k, v]) => `  ${k}: ${v};`)
    .join("\n");

  return `${selector} {\n${body}\n}`;
}

/** Tokens that must be re-declared inside a scope because :root resolved them against root values. */
const SCOPE_CONSTANTS = {"--card": "var(--surface)", "--sidebar-ring": "var(--foreground)"};

/**
 * Live preview CSS. Like HeroUI: page level gets colours only (toolbar + chrome), content level
 * (preview + its popups) gets colours, radius, font and field radius. Light rules use
 * `:not(.dark *)`, dark rules `.dark`.
 */
export function generatePreviewCss(variables: ThemeVariables): string {
  const theme = computeSkillTheme(variables);
  const page = `#${THEME_BUILDER_PAGE_ID}`;
  const content = `#${THEME_BUILDER_CONTENT_ID}`;
  // Base UI portals render popups into <body>; while a preview Select is open, theme its popup too.
  const previewPopup =
    'body:has(#theme-builder-content [data-slot="select-trigger"][data-popup-open]) [data-slot="select-content"]';
  const colorScopes = (mode: Mode, sels: string[]) =>
    sels.map((s) => (mode === "dark" ? `.dark ${s}` : `${s}:not(.dark *)`)).join(",\n");
  const common = {
    "--font-sans": `"${theme.fontMeta.family}", sans-serif`,
    "--radius": theme.radius,
    "--field-radius": fieldRadiusIsDefault(theme) ? `calc(${theme.radius} * 1.5)` : theme.fieldRadius,
  };
  const parts: string[] = [];

  for (const mode of ["light", "dark"] as Mode[]) {
    parts.push(block(colorScopes(mode, [page, content, previewPopup]), {...theme[mode], ...SCOPE_CONSTANTS}));
  }
  parts.push(block(`${content},\n${previewPopup}`, {...common, "font-family": "var(--font-sans)"}));
  parts.push(
    `${FIELD_SELECTORS.map((s) => `${content} ${s}`).join(",\n")} {\n  border-radius: var(--field-radius);\n}`,
  );

  return parts.join("\n\n");
}
